-- =============================================
-- 1. TABLAS AUXILIARES ESTÁTICAS
-- =============================================

create table rol (
    id integer generated by default as identity primary key,
    nombre varchar not null unique -- 'admin', 'user'
);

create table modalidad (
    id integer generated by default as identity primary key,
    nombre varchar not null unique -- 'inPerson', 'hybrid', 'remote', 'async'
);

create table nivel (
    id integer generated by default as identity primary key,
    nombre varchar not null unique -- 'easy', 'medium', 'hard'
);

create table tipo_certificado (
    id integer generated by default as identity primary key,
    nombre varchar not null unique -- 'course', 'training', 'postSecondary', 'universityLevel', 'language'
);

create table tipo_reporte (
    id integer generated by default as identity primary key,
    nombre varchar not null unique -- 'technical', 'courseRelated', 'suggestion', 'bug'
);

create table estado_reporte (
    id integer generated by default as identity primary key,
    nombre varchar not null unique -- 'pending', 'inReview', 'resolved', 'ignored'
);

create table tipo_accion (
    id integer generated by default as identity primary key,
    nombre varchar not null unique -- 'created', 'updated', 'deleted', 'approved', 'rejected'
);


-- =============================================
-- 2. CUENTAS
-- =============================================

create table usuario (
    id uuid primary key references auth.users (id) on delete cascade,
    nombre varchar not null,
    apellido varchar,
    email varchar not null unique,
    fecha_nacimiento date,
    foto_perfil text,
    biografia text,
    ubicacion varchar,
    user_preferencia varchar,
    rol_id integer default 2 references rol (id),
    esta_activo boolean default true,
    fecha_registro timestamp default current_timestamp,
    fecha_actualizacion timestamp default current_timestamp
);


-- =============================================
-- 3. CURSOS
-- =============================================

create table categoria (
    id integer generated by default as identity primary key,
    nombre varchar not null unique,
    descripcion text,
    icono_url text
);

create table curso (
    id integer generated by default as identity primary key,
    nombre_propietario varchar,
    categoria_id integer references categoria (id),
    titulo varchar not null,
    descripcion_corta text,
    descripcion_larga text,
    modalidad_id integer references modalidad (id),
    nivel_id integer references nivel (id),
    tipo_certificado_id integer references tipo_certificado (id),
    duracion_dias integer,
    precio numeric default 0,
    fecha_inicio date,
    fecha_termino date,
    fecha_max_inscripcion date,
    fecha_publicacion timestamp default current_timestamp,
    enlace_inscripcion text,
    cupos_disponibles integer,
    esta_activo boolean default true
);

create table curso_usuario (
    id integer generated by default as identity primary key,
    usuario_id uuid references usuario (id),
    curso_id integer references curso (id),
    fecha_adquisicion timestamp default current_timestamp,
    fecha_finalizacion timestamp,
    unique (usuario_id, curso_id)
);


-- =============================================
-- 5. INTERACCIONES DEL USUARIO
-- =============================================

create table favorito (
    id integer generated by default as identity primary key,
    usuario_id uuid references usuario (id),
    curso_id integer references curso (id),
    fecha timestamp default current_timestamp,
    unique (usuario_id, curso_id)
);

create table valoracion (
    id integer generated by default as identity primary key,
    usuario_id uuid references usuario (id),
    curso_id integer references curso (id),
    puntuacion integer not null check (puntuacion between 1 and 5),
    comentario text,
    esta_activa boolean default true,
    esta_aprobada boolean default false,
    fecha_aprobacion timestamp,
    ip_address varchar,
    user_agent text,
    fecha timestamp default current_timestamp,
    unique (usuario_id, curso_id)
);


-- =============================================
-- 7. REPORTES
-- =============================================

create table reporte (
    id integer generated by default as identity primary key,
    usuario_id uuid references usuario (id),
    tipo_reporteId integer references tipo_reporte (id),
    entidad_tipo varchar not null, -- 'course', 'user', 'review', 'institution'
    entidad_id varchar,
    mensaje text not null,
    estado_id integer default 1 references estado_reporte (id),
    respuesta_admin text,
    fecha_creacion timestamp default current_timestamp,
    fecha_resolucion timestamp
);


-- =============================================
-- 8. PROMOCIONES
-- =============================================

create table promocion (
    id integer generated by default as identity primary key,
    curso_id integer references curso (id),
    titulo varchar not null,
    descuento_porcentaje integer not null check (descuento_porcentaje between 1 and 100),
    motivo varchar,
    etiqueta_url text,
    fecha_inicio date not null,
    fecha_finalizacion date not null,
    orden integer,
    esta_activa boolean default true
);


-- =============================================
-- 9. AUDITORÍA
-- =============================================

create table auditoria (
    id integer generated by default as identity primary key,
    usuario_id uuid references usuario (id) on delete set null,
    tipo_accionId integer references tipo_accion (id),
    entidad_tipo varchar not null,
    entidad_id varchar,
    valores_anteriores text,
    valores_nuevos text,
    ip_address varchar,
    user_agent text,
    request_id varchar,
    exito boolean default true,
    fecha timestamp default current_timestamp
);

create index on auditoria (entidad_tipo, entidad_id);
create index on auditoria (usuario_id, fecha);
create index on auditoria (request_id);